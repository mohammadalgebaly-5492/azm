-- المرحلة الثانية (PostgreSQL / Supabase): هيكل WBS وجدول الكميات وخط الأساس
-- الكميات تُخزن بالألف (qty_milli = الكمية × 1000) لتجنب أخطاء الكسور. المبالغ بالهللة.

CREATE TABLE wbs_nodes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id  BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    parent_id   BIGINT REFERENCES wbs_nodes(id),
    code        TEXT NOT NULL,                 -- 01 أو 01.02 أو 01.02.03
    name        TEXT NOT NULL,
    level       INTEGER NOT NULL CHECK (level BETWEEN 1 AND 4),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by  BIGINT NOT NULL REFERENCES users(id),
    UNIQUE (project_id, code)
);
CREATE INDEX wbs_parent ON wbs_nodes(parent_id);

CREATE TABLE boq_items (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id   BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    wbs_id       BIGINT NOT NULL REFERENCES wbs_nodes(id),
    code         TEXT NOT NULL,                -- 01.02-SE-010
    ref_no       TEXT,                         -- رقم البند في جدول كميات المالك
    description  TEXT NOT NULL,
    item_type    TEXT NOT NULL CHECK (item_type IN ('supply','exec','both')),
    unit         TEXT NOT NULL,
    qty_milli    BIGINT NOT NULL CHECK (qty_milli > 0),
    unit_rate    BIGINT NOT NULL CHECK (unit_rate >= 0),
    amount       BIGINT NOT NULL CHECK (amount >= 0),
    notes        TEXT,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by   BIGINT NOT NULL REFERENCES users(id),
    updated_at   TIMESTAMPTZ,
    UNIQUE (project_id, code),
    CHECK (amount = div(qty_milli::numeric * unit_rate + 500, 1000))
);
CREATE INDEX boq_wbs ON boq_items(wbs_id);

ALTER TABLE projects ADD COLUMN baseline_total BIGINT;
ALTER TABLE projects ADD COLUMN baseline_approved_at TIMESTAMPTZ;
ALTER TABLE projects ADD COLUMN baseline_approved_by BIGINT REFERENCES users(id);

-- بعد اعتماد خط الأساس: جدول الكميات وهيكل WBS مجمّدان على مستوى قاعدة البيانات
CREATE FUNCTION baseline_lock() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE pid BIGINT;
BEGIN
    pid := CASE WHEN TG_OP = 'INSERT' THEN NEW.project_id ELSE OLD.project_id END;
    IF (SELECT baseline_approved_at FROM projects WHERE id = pid) IS NOT NULL THEN
        RAISE EXCEPTION 'baseline approved: % is locked', TG_ARGV[0] USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END $$;
CREATE TRIGGER boq_locked BEFORE INSERT OR UPDATE OR DELETE ON boq_items
    FOR EACH ROW EXECUTE FUNCTION baseline_lock('BOQ');
CREATE TRIGGER wbs_locked BEFORE INSERT OR DELETE ON wbs_nodes
    FOR EACH ROW EXECUTE FUNCTION baseline_lock('WBS');

DO $$
DECLARE t record;
BEGIN
    FOR t IN SELECT tablename FROM pg_tables WHERE schemaname = 'public' LOOP
        EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t.tablename);
        IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
            EXECUTE format('REVOKE ALL ON public.%I FROM anon, authenticated', t.tablename);
        END IF;
    END LOOP;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
        REVOKE EXECUTE ON FUNCTION baseline_lock() FROM PUBLIC, anon, authenticated;
    END IF;
END $$;
