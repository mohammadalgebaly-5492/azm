-- الجدول الزمني للمتابعة (الدستور، البند 3.4)، وإنجاز خطوات نطاق العمل (البند 3.7)، وجدول الدفعات التعاقدية (البند 3.2).
-- النسب بأجزاء من عشرة آلاف.
CREATE TABLE activities (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id       BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    code             TEXT NOT NULL,                       -- 01.02-A010
    name             TEXT NOT NULL,
    wbs_id           BIGINT NOT NULL REFERENCES wbs_nodes(id),
    boq_item_id      BIGINT REFERENCES boq_items(id),
    planned_start    DATE NOT NULL,
    planned_finish   DATE NOT NULL,
    actual_start     DATE,
    actual_finish    DATE,
    notes            TEXT,
    created_at       TIMESTAMPTZ NOT NULL,
    created_by       BIGINT NOT NULL REFERENCES users(id),
    UNIQUE (project_id, code),
    CHECK (planned_finish >= planned_start),
    CHECK (actual_finish IS NULL OR (actual_start IS NOT NULL AND actual_finish >= actual_start))
);
CREATE INDEX activities_project ON activities(project_id);

CREATE TABLE activity_links (
    activity_id      BIGINT NOT NULL REFERENCES activities(id) ON DELETE CASCADE,
    predecessor_id   BIGINT NOT NULL REFERENCES activities(id) ON DELETE CASCADE,
    PRIMARY KEY (activity_id, predecessor_id),
    CHECK (activity_id != predecessor_id)
);

ALTER TABLE projects ADD COLUMN schedule_reviewed_at TIMESTAMPTZ;
ALTER TABLE projects ADD COLUMN schedule_reviewed_by BIGINT REFERENCES users(id);
ALTER TABLE projects ADD COLUMN schedule_approved_at TIMESTAMPTZ;
ALTER TABLE projects ADD COLUMN schedule_approved_by BIGINT REFERENCES users(id);

ALTER TABLE scope_steps ADD COLUMN finished_on DATE;
ALTER TABLE scope_steps ADD COLUMN finished_by BIGINT REFERENCES users(id);
ALTER TABLE allocations ADD COLUMN activity_id BIGINT REFERENCES activities(id);

CREATE TABLE payment_milestones (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contract_id          BIGINT NOT NULL REFERENCES contracts(id) ON DELETE CASCADE,
    code                 TEXT NOT NULL UNIQUE,            -- P-2026-001-CON-01-PAY-01
    seq                  INTEGER NOT NULL CHECK (seq > 0),
    description          TEXT NOT NULL,
    activity_id          BIGINT NOT NULL REFERENCES activities(id),
    required_progress_bp INTEGER NOT NULL DEFAULT 10000 CHECK (required_progress_bp BETWEEN 1 AND 10000),
    share_bp             INTEGER NOT NULL CHECK (share_bp BETWEEN 1 AND 10000),
    notes                TEXT,
    created_at           TIMESTAMPTZ NOT NULL,
    created_by           BIGINT NOT NULL REFERENCES users(id)
);

