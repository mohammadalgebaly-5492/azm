-- مستويات صلاحية مهندس المشروع وتقييمه الآلي (الدستور، البند 4.4).
CREATE TABLE engineer_levels (
    user_id   BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    level     TEXT NOT NULL CHECK (level IN ('full','restricted','suspended')),
    reason    TEXT NOT NULL,
    set_at    TIMESTAMPTZ NOT NULL,
    set_by    BIGINT NOT NULL REFERENCES users(id)
);

CREATE TABLE authority_changes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    from_level  TEXT NOT NULL,
    to_level    TEXT NOT NULL,
    reason      TEXT NOT NULL,
    set_at      TIMESTAMPTZ NOT NULL,
    set_by      BIGINT NOT NULL REFERENCES users(id)
);

ALTER TABLE daily_reports ADD COLUMN needs_pm BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE daily_reports ADD COLUMN pm_checked_at TIMESTAMPTZ;
ALTER TABLE daily_reports ADD COLUMN pm_checked_by BIGINT REFERENCES users(id);
ALTER TABLE daily_reports ADD COLUMN times_returned INTEGER NOT NULL DEFAULT 0;

DO $$
DECLARE t record;
BEGIN
    FOR t IN SELECT tablename FROM pg_tables WHERE schemaname = 'public' LOOP
        EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t.tablename);
        IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
            EXECUTE format('REVOKE ALL ON public.%I FROM anon, authenticated', t.tablename);
        END IF;
    END LOOP;
END $$;
