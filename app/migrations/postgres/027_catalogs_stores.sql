CREATE TABLE stock_items (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    material_code TEXT NOT NULL UNIQUE,                  -- مكوّن من دليل المواد (السقالات)
    daily_rate    BIGINT NOT NULL DEFAULT 0              -- هللة لكل قطعة في اليوم، سواء كانت ملكًا أو مستأجرة
);

CREATE TABLE stock_moves (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          TEXT NOT NULL UNIQUE,                  -- STM-00001
    kind          TEXT NOT NULL CHECK (kind IN ('receive','issue','install','dismantle','return','loss')),
    material_code TEXT NOT NULL,
    qty           INTEGER NOT NULL CHECK (qty > 0),
    project_id    BIGINT REFERENCES projects(id) ON DELETE CASCADE,
    boq_item_id   BIGINT REFERENCES boq_items(id),
    place         TEXT CHECK (place IS NULL OR place IN ('store','site','use')),
    on_date       DATE NOT NULL,
    reason        TEXT,
    created_at    TIMESTAMPTZ NOT NULL,
    created_by    BIGINT NOT NULL REFERENCES users(id)
);
CREATE INDEX stock_moves_project ON stock_moves(project_id, material_code);
