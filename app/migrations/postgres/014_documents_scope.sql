-- وثائق المشروع (الدستور، البند 3.1) ونطاق العمل وخطوات التنفيذ (البند 3.7)، وربط التخصيص بخطوة النطاق (البند 3.6).
-- النسب بأجزاء من عشرة آلاف.
CREATE TABLE documents (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id    BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    code          TEXT NOT NULL UNIQUE,                   -- P-2026-001-DOC-DRW-0001
    title         TEXT NOT NULL,
    doc_type      TEXT NOT NULL,                          -- دليل أنواع الوثائق
    wbs_id        BIGINT REFERENCES wbs_nodes(id) ON DELETE SET NULL,
    boq_item_id   BIGINT REFERENCES boq_items(id) ON DELETE SET NULL,
    issuer        TEXT NOT NULL CHECK (issuer IN ('company','owner','consultant','other')),
    issuer_ref    TEXT,
    issued_on     DATE NOT NULL,
    summary       TEXT,
    reviewed_at   TIMESTAMPTZ,
    reviewed_by   BIGINT REFERENCES users(id),
    created_at    TIMESTAMPTZ NOT NULL,
    created_by    BIGINT NOT NULL REFERENCES users(id)
);
CREATE INDEX documents_project ON documents(project_id);

CREATE TABLE document_revisions (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id         BIGINT NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
    rev_no              INTEGER NOT NULL CHECK (rev_no >= 0),
    rev_date            DATE NOT NULL,
    status              TEXT NOT NULL DEFAULT 'review' CHECK (status IN ('review','approved','approved_notes','rejected')),
    approver_entity_id  BIGINT REFERENCES entities(id),
    approver_person_id  BIGINT REFERENCES entity_people(id),
    approved_on         DATE,
    notes               TEXT,
    created_at          TIMESTAMPTZ NOT NULL,
    created_by          BIGINT NOT NULL REFERENCES users(id),
    decided_at          TIMESTAMPTZ,
    decided_by          BIGINT REFERENCES users(id),
    UNIQUE (document_id, rev_no)
);

CREATE TABLE item_scopes (
    boq_item_id   BIGINT PRIMARY KEY REFERENCES boq_items(id) ON DELETE CASCADE,
    project_id    BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    summary       TEXT NOT NULL,
    includes      TEXT NOT NULL,
    excludes      TEXT,
    reviewed_at   TIMESTAMPTZ,
    reviewed_by   BIGINT REFERENCES users(id),
    updated_at    TIMESTAMPTZ NOT NULL,
    updated_by    BIGINT NOT NULL REFERENCES users(id)
);

CREATE TABLE item_scope_docs (
    boq_item_id   BIGINT NOT NULL REFERENCES boq_items(id) ON DELETE CASCADE,
    document_id   BIGINT NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
    PRIMARY KEY (boq_item_id, document_id)
);

CREATE TABLE scope_steps (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id    BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    boq_item_id   BIGINT NOT NULL REFERENCES boq_items(id) ON DELETE CASCADE,
    code          TEXT NOT NULL,                          -- 01.02-SE-010-ST01
    seq           INTEGER NOT NULL CHECK (seq > 0),
    name          TEXT NOT NULL,
    weight_bp     INTEGER NOT NULL CHECK (weight_bp BETWEEN 1 AND 10000),
    party         TEXT NOT NULL CHECK (party IN ('crew','subcontractor')),
    crew_id       BIGINT REFERENCES crews(id),
    entity_id     BIGINT REFERENCES entities(id),
    equipment_id  BIGINT REFERENCES equipment(id),
    notes         TEXT,
    created_at    TIMESTAMPTZ NOT NULL,
    created_by    BIGINT NOT NULL REFERENCES users(id),
    UNIQUE (project_id, code),
    CHECK ((party = 'crew' AND crew_id IS NOT NULL AND entity_id IS NULL)
        OR (party = 'subcontractor' AND entity_id IS NOT NULL AND crew_id IS NULL))
);
CREATE INDEX scope_steps_item ON scope_steps(boq_item_id);

ALTER TABLE allocations ADD COLUMN step_id BIGINT REFERENCES scope_steps(id);

