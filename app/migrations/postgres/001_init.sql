-- المرحلة الأولى (PostgreSQL / Supabase): الحسابات والجلسات والمشروعات والطاقم والسجل
-- المبالغ تُخزن بالهللة كأعداد صحيحة. الأوقات timestamptz (UTC).

CREATE TABLE counters (
    key   TEXT PRIMARY KEY,
    value BIGINT NOT NULL
);

CREATE TABLE users (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                 TEXT NOT NULL UNIQUE,              -- USR-PM-03
    username             TEXT NOT NULL UNIQUE,              -- يُخزن بحروف صغيرة
    email                TEXT NOT NULL UNIQUE,
    full_name            TEXT NOT NULL,
    role                 TEXT NOT NULL CHECK (role IN ('admin','pm','director','accountant','viewer','owner_rep','consultant')),
    status               TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','disabled')),
    password_hash        TEXT NOT NULL,
    must_change_password BOOLEAN NOT NULL DEFAULT TRUE,
    failed_attempts      INTEGER NOT NULL DEFAULT 0,
    locked_until         TIMESTAMPTZ,
    last_login_at        TIMESTAMPTZ,
    password_changed_at  TIMESTAMPTZ,
    phone                TEXT,
    job_title            TEXT,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by           BIGINT REFERENCES users(id)
);

CREATE TABLE sessions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash  TEXT NOT NULL UNIQUE,
    user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    csrf_token  TEXT NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL,
    last_seen   TIMESTAMPTZ NOT NULL,
    expires_at  TIMESTAMPTZ NOT NULL,
    ip          TEXT,
    user_agent  TEXT
);
CREATE INDEX sessions_user ON sessions(user_id);

CREATE TABLE projects (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code             TEXT NOT NULL UNIQUE,                   -- P-2026-014
    name             TEXT NOT NULL,
    client           TEXT,
    consultant       TEXT,
    location         TEXT,
    contract_no      TEXT,
    contract_value   BIGINT CHECK (contract_value IS NULL OR contract_value >= 0),
    start_date       DATE,
    end_date         DATE,
    status           TEXT NOT NULL DEFAULT 'setup' CHECK (status IN ('setup','active','closed')),
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by       BIGINT NOT NULL REFERENCES users(id),
    CHECK (end_date IS NULL OR start_date IS NULL OR end_date > start_date)
);

CREATE TABLE project_members (
    project_id   BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    user_id      BIGINT NOT NULL REFERENCES users(id),
    assigned_at  TIMESTAMPTZ NOT NULL,
    assigned_by  BIGINT NOT NULL REFERENCES users(id),
    PRIMARY KEY (project_id, user_id)
);
CREATE INDEX project_members_user ON project_members(user_id);

-- سجل تدقيق للإضافة فقط
CREATE TABLE audit_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at          TIMESTAMPTZ NOT NULL,
    actor_id    BIGINT REFERENCES users(id),
    action      TEXT NOT NULL,
    entity      TEXT,
    entity_id   BIGINT,
    project_id  BIGINT REFERENCES projects(id),
    details     JSONB,
    ip          TEXT
);
CREATE INDEX audit_project ON audit_log(project_id);
CREATE INDEX audit_entity ON audit_log(entity, entity_id);

CREATE FUNCTION audit_log_append_only() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'audit_log is append-only' USING ERRCODE = 'integrity_constraint_violation';
END $$;
CREATE TRIGGER audit_no_update BEFORE UPDATE OR DELETE ON audit_log
    FOR EACH ROW EXECUTE FUNCTION audit_log_append_only();
CREATE TRIGGER audit_no_truncate BEFORE TRUNCATE ON audit_log
    FOR EACH STATEMENT EXECUTE FUNCTION audit_log_append_only();

-- Supabase: التطبيق يتصل مباشرة بقاعدة البيانات، فلا شيء من هذه الجداول يُتاح عبر REST API بمفتاح anon
DO $$
DECLARE t record;
BEGIN
    FOR t IN SELECT tablename FROM pg_tables WHERE schemaname = 'public' LOOP
        EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t.tablename);
        IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
            EXECUTE format('REVOKE ALL ON public.%I FROM anon, authenticated', t.tablename);
        END IF;
    END LOOP;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
        REVOKE EXECUTE ON FUNCTION audit_log_append_only() FROM PUBLIC, anon, authenticated;
    END IF;
END $$;
